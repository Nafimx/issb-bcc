/* iq-nonverbal.js — non-verbal reasoning, the half of the ISSB paper the
   verbal bank does not cover: figure series, mirror images, odd figure out,
   figure analogy, counting figures, dice, paper folding and number matrices.

   Every item is CONSTRUCTED so the key is known by build, never by inspection:
   the correct option is generated by applying the rule, the distractors by
   applying deliberately wrong rules. Options are SVG markup and carry
   render:"svg" so the page draws them instead of escaping them.

   Requires core.js (randInt, pick, seededShuffle). */
(function (global) {
  "use strict";
  const { randInt, pick, seededShuffle } = global.ISSB;

  const S = 90;                                   // option box size
  const INK = "#e9efe9";                          // strokes read on the dark card
  const box = (inner, s) =>
    '<svg viewBox="0 0 ' + S + " " + S + '" width="' + (s || 78) + '" height="' + (s || 78) +
    '" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">' +
    '<rect x="1" y="1" width="' + (S - 2) + '" height="' + (S - 2) + '" fill="none" stroke="#3d4d44" stroke-width="1.5"/>' +
    '<g fill="none" stroke="' + INK + '" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round">' +
    inner + "</g></svg>";

  /* four distinct numeric options around a value */
  function numOptions(rng, right, candidates) {
    const seen = new Set([String(right)]);
    const out = [];
    for (const c of candidates) {
      const k = String(c);
      if (seen.has(k) || !isFinite(c) || c < 0) continue;
      seen.add(k); out.push(String(c));
      if (out.length === 3) break;
    }
    let bump = 1;
    while (out.length < 3 && bump < 40) {
      const c = right + bump;
      if (!seen.has(String(c))) { seen.add(String(c)); out.push(String(c)); }
      bump++;
    }
    return seededShuffle([String(right), ...out], rng);
  }

  /* choose 4 distinct options, remember where the right one landed */
  function frame(rng, cat, q, right, wrongs, explain) {
    const seen = new Set([right]);
    const opts = [];
    for (const w of wrongs) {
      if (opts.length === 3) break;
      if (!seen.has(w)) { seen.add(w); opts.push(w); }
    }
    const all = seededShuffle([right, ...opts], rng);
    return {
      cat, q, options: all, answerIndex: all.indexOf(right),
      explain: explain, render: "svg",
    };
  }

  /* ---------- shapes, drawn at a given rotation ---------- */
  const C = S / 2;
  const rot = (d, inner) => '<g transform="rotate(' + d + " " + C + " " + C + ')">' + inner + "</g>";

  const SHAPES = {
    arrow:   '<path d="M45 20 L45 70 M45 20 L34 33 M45 20 L56 33"/>',
    flag:    '<path d="M32 70 L32 20 L62 30 L32 40"/>',
    tee:     '<path d="M25 30 L65 30 M45 30 L45 68"/>',
    hook:    '<path d="M30 25 L30 60 q0 10 12 10 t12 -10"/>',
    zigzag:  '<path d="M26 62 L38 34 L50 62 L62 34"/>',
    kite:    '<path d="M45 18 L66 45 L45 72 L24 45z M24 45 L66 45"/>',
    chevron: '<path d="M24 60 L45 26 L66 60 M45 26 L45 68"/>',
    cross:   '<path d="M45 22 L45 68 M22 30 L68 60 M68 30 L22 60"/>',
    step:    '<path d="M22 62 L22 44 L45 44 L45 26 L68 26"/>',
    fork:    '<path d="M45 68 L45 40 M45 40 L28 22 M45 40 L62 22"/>',
    bowtie:  '<path d="M24 26 L66 26 L24 64 L66 64z"/>',
    comb:    '<path d="M22 26 L68 26 M28 26 L28 64 M45 26 L45 58 M62 26 L62 64"/>',
    pennant: '<path d="M28 68 L28 22 L68 34 L28 46z"/>',
    lightning:'<path d="M50 20 L30 48 L44 48 L38 70 L62 40 L48 40z"/>',
  };
  const DOT = '<circle cx="68" cy="24" r="5" fill="' + INK + '"/>';

  /* ---------- 1. figure series: the shape turns by a fixed step ---------- */
  function figureSeries(rng) {
    const key = pick(rng, Object.keys(SHAPES));
    const shape = SHAPES[key] + DOT;
    const step = pick(rng, [45, 90, 135, -90, 180]);
    const start = pick(rng, [0, 45, 90]);
    const seq = [0, 1, 2].map((i) => box(rot(start + i * step, shape), 66)).join("");
    const right = box(rot(start + 3 * step, shape));
    const wrongs = [
      box(rot(start + 2 * step, shape)),
      box(rot(start + 4 * step, shape)),
      box(rot(start - step, shape)),
      box(rot(start + 3 * step + 45, shape)),
    ];
    return frame(rng, "Figure Series",
      "The figure turns by the same amount each time. Which figure comes next?<div class=\"figrow\">" + seq + "<span class=\"qmark\">?</span></div>",
      right, wrongs,
      "Each step turns the figure " + Math.abs(step) + "° " + (step > 0 ? "clockwise" : "anti-clockwise") + ".");
  }

  /* ---------- 2. mirror image ---------- */
  function mirrorImage(rng) {
    const key = pick(rng, Object.keys(SHAPES));
    const shape = SHAPES[key] + DOT;
    const vertical = rng() < 0.5;
    const flipped = vertical
      ? '<g transform="translate(' + S + ',0) scale(-1,1)">' + shape + "</g>"
      : '<g transform="translate(0,' + S + ') scale(1,-1)">' + shape + "</g>";
    const other = vertical
      ? '<g transform="translate(0,' + S + ') scale(1,-1)">' + shape + "</g>"
      : '<g transform="translate(' + S + ',0) scale(-1,1)">' + shape + "</g>";
    const right = box(flipped);
    const wrongs = [box(shape), box(rot(180, shape)), box(other), box(rot(90, flipped))];
    return frame(rng, "Mirror Image",
      "Which option is the mirror image of the figure on the left, seen in a " +
      (vertical ? "vertical" : "horizontal") + " mirror?" +
      "<div class=\"figrow\">" + box(shape, 66) + "</div>",
      right, wrongs,
      vertical ? "A vertical mirror flips left and right but not top and bottom."
               : "A horizontal mirror flips top and bottom but not left and right.");
  }

  /* ---------- 3. odd figure out ---------- */
  function oddFigure(rng) {
    const key = pick(rng, Object.keys(SHAPES));
    /* the marker dot breaks the symmetry of shapes like the kite, so two
       rotations can never render identically */
    const shape = SHAPES[key] + DOT;
    const angles = seededShuffle([0, 90, 180, 270], rng).slice(0, 3);
    const same = angles.map((a) => box(rot(a, shape)));
    const other = pick(rng, Object.keys(SHAPES).filter((k) => k !== key));
    const odd = box(rot(pick(rng, [0, 90, 180]), SHAPES[other] + DOT));
    return frame(rng, "Odd Figure Out",
      "Three of these are the same figure simply turned round. Which one is different?",
      odd, same, "The other three are one figure at different rotations; this one is a different figure.");
  }

  /* ---------- 4. figure analogy ---------- */
  function figureAnalogy(rng) {
    const key = pick(rng, Object.keys(SHAPES));
    const shape = SHAPES[key] + DOT;
    const step = pick(rng, [90, 180, -90]);
    const other = pick(rng, Object.keys(SHAPES).filter((k) => k !== key));
    const shape2 = SHAPES[other] + DOT;
    const right = box(rot(step, shape2));
    const wrongs = [
      box(shape2),
      box(rot(step + 90, shape2)),
      box(rot(-step, shape2)),
      box(rot(step + 180, shape2)),
    ];
    return frame(rng, "Figure Analogy",
      "The first figure changes into the second in a certain way. Apply the same change to the third figure." +
      "<div class=\"figrow\">" + box(shape, 62) + '<span class="qmark">:</span>' + box(rot(step, shape), 62) +
      '<span class="qmark">::</span>' + box(shape2, 62) + '<span class="qmark">: ?</span></div>',
      right, wrongs, "The figure is turned " + Math.abs(step) + "° " + (step > 0 ? "clockwise" : "anti-clockwise") + ".");
  }

  /* ---------- 5. counting figures ----------
     A fan of n lines inside a triangle makes exactly n(n+1)/2 triangles, so
     the count is arithmetic, not a guess. */
  function countFigures(rng) {
    if (rng() < 0.5) {
      // a triangle cut by lines from the apex: n sections give n(n+1)/2 triangles
      const n = randInt(rng, 2, 9);
      const total = (n * (n + 1)) / 2;
      let inner = '<path d="M10 78 L80 78 L45 14z"/>';
      for (let i = 1; i < n; i++) {
        const x = 10 + (70 * i) / n;
        inner += '<path d="M45 14 L' + x.toFixed(1) + ' 78"/>';
      }
      return {
        cat: "Counting Figures",
        q: "How many triangles are there in this figure?<div class=\"figrow\">" + box(inner, 110) + "</div>",
        options: numOptions(rng, total, [total + 1, total - 1, total + n, total - n, total + 2]),
        answerIndex: -1,
        explain: "The apex lines cut the base into " + n + " parts, so the count is " + n + "×" + (n + 1) + "/2 = " + total + ".",
        render: "svg", _right: String(total),
      };
    }
    // an n x n grid of squares holds n^2 + (n-1)^2 + ... + 1 squares
    const n = randInt(rng, 2, 5);
    let total = 0;
    for (let k = 1; k <= n; k++) total += k * k;
    let inner = "";
    const step = 62 / n;
    for (let i = 0; i <= n; i++) {
      const p = 14 + i * step;
      inner += '<path d="M14 ' + p.toFixed(1) + " L76 " + p.toFixed(1) + '"/>';
      inner += '<path d="M' + p.toFixed(1) + " 14 L" + p.toFixed(1) + ' 76"/>';
    }
    return {
      cat: "Counting Figures",
      q: "How many squares of any size are there in this figure?<div class=\"figrow\">" + box(inner, 110) + "</div>",
      options: numOptions(rng, total, [n * n, total + 1, total - 1, total + n]),
      answerIndex: -1,
      explain: "A " + n + "×" + n + " grid holds " + n + "² + … + 1² = " + total + " squares.",
      render: "svg", _right: String(total),
    };
  }

  /* ---------- 6. dice: opposite faces ---------- */
  function dice(rng) {
    const a = randInt(rng, 1, 6);
    const opposite = 7 - a;                       // standard die: opposite faces total seven
    const wrongs = [1, 2, 3, 4, 5, 6].filter((v) => v !== opposite && v !== a);
    const pips = (v) => {
      const P = { 1: [[45, 45]], 2: [[28, 28], [62, 62]], 3: [[28, 28], [45, 45], [62, 62]],
        4: [[28, 28], [62, 28], [28, 62], [62, 62]], 5: [[28, 28], [62, 28], [45, 45], [28, 62], [62, 62]],
        6: [[28, 25], [62, 25], [28, 45], [62, 45], [28, 65], [62, 65]] };
      return '<rect x="16" y="16" width="58" height="58" rx="8"/>' +
        P[v].map((p) => '<circle cx="' + p[0] + '" cy="' + p[1] + '" r="5" fill="' + INK + '"/>').join("");
    };
    if (rng() < 0.5) {
      return {
        cat: "Dice",
        q: "On a standard die the numbers on opposite faces add up to seven. Which number is on the face opposite this one?" +
           "<div class=\"figrow\">" + box(pips(a), 84) + "</div>",
        options: seededShuffle([String(opposite), ...seededShuffle(wrongs, rng).slice(0, 3).map(String)], rng),
        answerIndex: -1, explain: "7 − " + a + " = " + opposite + ".",
        render: "svg", _right: String(opposite),
      };
    }
    // two faces are visible, so the four hidden faces total 21 minus what is shown
    let b = randInt(rng, 1, 6);
    while (b === a || b === opposite) b = randInt(rng, 1, 6);
    const hidden = 21 - a - b;
    return {
      cat: "Dice",
      q: "These two faces of a standard die can be seen. The six faces total 21. What do the four hidden faces add up to?" +
         "<div class=\"figrow\">" + box(pips(a), 78) + box(pips(b), 78) + "</div>",
      options: numOptions(rng, hidden, [hidden + 1, hidden - 1, 21 - a, hidden + a]),
      answerIndex: -1, explain: "21 − " + a + " − " + b + " = " + hidden + ".",
      render: "svg", _right: String(hidden),
    };
  }

  /* ---------- 7. paper folding and punching ----------
     Fold once, punch h holes, unfold: the holes double and appear mirrored. */
  function paperFold(rng) {
    const holes = randInt(rng, 1, 6);
    const twice = rng() < 0.35;                 // folded twice: each punch makes four
    const total = holes * (twice ? 4 : 2);
    const vertical = rng() < 0.5;
    void 0;
    void 0;
    /* keep every punch clear of the crease: on the crease it would pass
       through one layer only and the count would not double */
    const pts = [];
    for (let i = 0; i < holes; i++) {
      const x = vertical ? 20 + (i % 3) * 7 : 22 + (i % 3) * 14;
      const y = vertical ? 26 + Math.floor(i / 3) * 18 + (i % 2) * 9 : 20 + Math.floor(i / 3) * 8 + (i % 2) * 6;
      pts.push([x, y]);
    }
    const crease = vertical
      ? '<path d="M45 14 L45 76" stroke-dasharray="4 4"/>'
      : '<path d="M14 45 L76 45" stroke-dasharray="4 4"/>';
    const crease2 = twice
      ? (vertical ? '<path d="M14 45 L76 45" stroke-dasharray="4 4"/>' : '<path d="M45 14 L45 76" stroke-dasharray="4 4"/>')
      : "";
    const folded = '<rect x="14" y="14" width="62" height="62"/>' + crease + crease2 +
      pts.map((p) => '<circle cx="' + p[0] + '" cy="' + p[1] + '" r="4.5" fill="' + INK + '"/>').join("");
    return {
      cat: "Paper Folding",
      q: "A square sheet is folded along the dotted line" + (twice ? "s (twice)" : "") + " and " + holes + " hole" +
         (holes > 1 ? "s are" : " is") + " punched through. How many holes are there when the sheet is opened out?" +
         "<div class=\"figrow\">" + box(folded, 96) + "</div>",
      options: numOptions(rng, total, [holes, total + 1, total - 1, total + 2]),
      answerIndex: -1,
      explain: "Each punch passes through " + (twice ? "four" : "two") + " layers, so " + holes + " × " +
               (twice ? 4 : 2) + " = " + total + ".",
      render: "svg", _right: String(total),
    };
  }

  /* ---------- 8. number matrix ---------- */
  function numberMatrix(rng) {
    const kind = randInt(rng, 1, 3);
    const a = randInt(rng, 2, 9), b = randInt(rng, 2, 9), c = randInt(rng, 2, 9);
    const d = randInt(rng, 2, 9), e = randInt(rng, 2, 9), f = randInt(rng, 2, 9);
    let rowOf, why;
    if (kind === 1) { rowOf = (x, y) => x * y; why = "In each row the third number is the first multiplied by the second."; }
    else if (kind === 2) { rowOf = (x, y) => x * y - x; why = "In each row: first × second − first."; }
    else { rowOf = (x, y) => x + y + x * y; why = "In each row: first + second + (first × second)."; }
    const ans = rowOf(e, f);
    const grid =
      '<table class="numgrid"><tr><td>' + a + "</td><td>" + b + "</td><td>" + rowOf(a, b) + "</td></tr>" +
      "<tr><td>" + c + "</td><td>" + d + "</td><td>" + rowOf(c, d) + "</td></tr>" +
      "<tr><td>" + e + "</td><td>" + f + '</td><td class="q">?</td></tr></table>';
    return {
      cat: "Number Matrix",
      q: "Find the number that should replace the question mark." + grid,
      options: numOptions(rng, ans, [ans + e, ans - f, ans + 2, ans - 2, ans + f, ans + 1]),
      answerIndex: -1, explain: why + " So " + e + " and " + f + " give " + ans + ".",
      render: "svg", _right: String(ans),
    };
  }

  /* the four generators above build their options directly, so resolve the key */
  function fixIndex(q) {
    if (q.answerIndex === -1 && q._right != null) {
      q.answerIndex = q.options.indexOf(q._right);
      delete q._right;
    }
    return q;
  }

  const GENERATORS = {
    "Figure Series": figureSeries,
    "Mirror Image": mirrorImage,
    "Odd Figure Out": oddFigure,
    "Figure Analogy": figureAnalogy,
    "Counting Figures": countFigures,
    "Dice": dice,
    "Paper Folding": paperFold,
    "Number Matrix": numberMatrix,
  };

  const wrapped = {};
  Object.keys(GENERATORS).forEach((k) => { wrapped[k] = (rng) => fixIndex(GENERATORS[k](rng)); });

  global.IQ_NONVERBAL = wrapped;
})(window);

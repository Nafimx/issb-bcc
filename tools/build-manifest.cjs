/* Regenerates assets/ppdt/manifest.json from whatever image files are in that
   folder, so adding pictures is: drop the files in, deploy. Runs on Vercel
   before every build, and can be run by hand with `npm run pics`. */
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "assets", "ppdt");
const OK = /\.(jpe?g|png|webp|gif|avif)$/i;

const files = fs.existsSync(dir)
  ? fs.readdirSync(dir).filter((f) => OK.test(f)).sort((a, b) => a.localeCompare(b, "en", { numeric: true }))
  : [];

const manifest = {
  note: "Generated by tools/build-manifest.cjs from the files in this folder. Drop pictures in and deploy.",
  count: files.length,
  pictures: files.map((f) => ({ file: f, title: path.basename(f, path.extname(f)).replace(/[-_]+/g, " ") })),
};

fs.writeFileSync(path.join(dir, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log("ppdt manifest: " + files.length + " picture(s)" + (files.length ? " — " + files.join(", ") : ""));

/* stamp the service worker with this build so a deploy retires the old cache */
const swPath = path.join(__dirname, "..", "sw.js");
const buildId = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "assets", "build.json"), "utf8")).build;
let sw = fs.readFileSync(swPath, "utf8");
sw = sw.replace(/const BUILD = "[^"]*";/, 'const BUILD = "' + buildId + '";');
fs.writeFileSync(swPath, sw);
console.log("service worker stamped with build " + buildId);
